export function hasCharacterBackdrop(characterId: string): boolean {
  const normId = characterId.toLowerCase().trim();
  return Boolean(CHARACTER_IMAGE_MAP[normId] || CHARACTER_IMAGE_MAP[normId.replace(/[^a-z0-9]/g, "-")]);
}
