/**
 * Returns the transparent PNG title logo path for a given movie/show ID or slug.
 * Returns null if no title logo exists, allowing clean fallback to stylized typography.
 */
export function getMovieLogo(movieId: string | undefined | null): string | null {
  if (!movieId) return null;
  const cleanId = movieId.trim().toLowerCase();
  
  if (MCU_LOGO_MAP[cleanId]) return MCU_LOGO_MAP[cleanId];
  if (MCU_LOGO_MAP[cleanId.replace(/_/g, "-")]) return MCU_LOGO_MAP[cleanId.replace(/_/g, "-")];
  if (MCU_LOGO_MAP[cleanId.replace(/-/g, "_")]) return MCU_LOGO_MAP[cleanId.replace(/-/g, "_")];
  
  return null;
}
